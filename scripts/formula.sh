#!/bin/sh
# Prints the Homebrew formula for a release.
#   usage: formula.sh VERSION SHA256
# VERSION is the release without its leading v (1.2.3); SHA256 is the checksum
# of the source archive attached to that release (amber-VERSION.tar.gz).
set -eu

if [ "$#" -ne 2 ]; then
  printf 'usage: %s VERSION SHA256\n' "$0" >&2
  exit 2
fi
version=$1
sha=$2

case $version in
[0123456789]*.[0123456789]*.[0123456789]*) ;;
*)
  printf 'Error: version must look like 1.2.3 (no leading v): %s\n' "$version" >&2
  exit 2
  ;;
esac
case $version in
*[!0123456789.]*)
  printf 'Error: version must only contain digits and dots: %s\n' "$version" >&2
  exit 2
  ;;
esac
case $sha in
*[!0123456789abcdef]*)
  printf 'Error: sha256 must be lowercase hex: %s\n' "$sha" >&2
  exit 2
  ;;
esac
if [ "${#sha}" -ne 64 ]; then
  printf 'Error: sha256 must be 64 characters: %s\n' "$sha" >&2
  exit 2
fi

# The formula is named amber-rex because Homebrew's own `amber` (the Crystal
# framework) already installs a bin/amber.
sed -e "s/@VERSION@/$version/g" -e "s/@SHA256@/$sha/g" <<'EOF'
# Generated by scripts/formula.sh when a release is published. Do not edit.
class AmberRex < Formula
  desc "Plugin manager for Rex"
  homepage "https://github.com/rawnly/amber"
  url "https://github.com/rawnly/amber/releases/download/v@VERSION@/amber-@VERSION@.tar.gz"
  sha256 "@SHA256@"
  license "Apache-2.0"
  head "https://github.com/rawnly/amber.git", branch: "main"

  depends_on "go" => :build
  depends_on "git"

  conflicts_with "amber", because: "both install an `amber` binary"

  def install
    libexec.install "amber.lua", "amber", "types"
    version_label = build.head? ? "dev" : "v#{version}"
    cd "cli" do
      system "go", "build",
             *std_go_args(output:  libexec/"bin/amber",
                          ldflags: "-s -w -X github.com/rawnly/amber/cli/internal/cli.Version=#{version_label}"),
             "./cmd/amber"
    end
    bin.install_symlink libexec/"bin/amber"
  end

  def caveats
    <<~EOS
      Load Amber from your Rex config (~/.config/rex/init.lua):

        local amber = dofile("#{opt_libexec}/amber.lua")

      The path stays the same when you upgrade. Reload Rex afterwards, then run `amber`.
    EOS
  end

  test do
    assert_match "amber version", shell_output("#{bin}/amber --version")
    assert_path_exists libexec/"amber.lua"
    assert_path_exists libexec/"amber/spec.lua"
  end
end
EOF
